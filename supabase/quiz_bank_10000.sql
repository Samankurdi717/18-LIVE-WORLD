create table if not exists public.kh_quiz_bank (
  id bigint generated by default as identity primary key,
  category text not null,
  translations jsonb not null,
  correct_option smallint not null check (correct_option between 0 and 3),
  status text not null default 'draft'
    check (status in ('draft','reviewed','published','archived')),
  source_note text,
  content_fingerprint text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint kh_quiz_bank_translations_object
    check (jsonb_typeof(translations) = 'object'),
  constraint kh_quiz_bank_has_four_languages
    check (
      translations ? 'ku' and translations ? 'fa'
      and translations ? 'ar' and translations ? 'en'
    ),
  constraint kh_quiz_bank_translation_shape
    check (
      jsonb_typeof(translations->'ku') = 'object'
      and jsonb_typeof(translations->'fa') = 'object'
      and jsonb_typeof(translations->'ar') = 'object'
      and jsonb_typeof(translations->'en') = 'object'
      and jsonb_typeof(translations->'ku'->'q') = 'string'
      and jsonb_typeof(translations->'fa'->'q') = 'string'
      and jsonb_typeof(translations->'ar'->'q') = 'string'
      and jsonb_typeof(translations->'en'->'q') = 'string'
      and jsonb_typeof(translations->'ku'->'a') = 'array'
      and jsonb_typeof(translations->'fa'->'a') = 'array'
      and jsonb_typeof(translations->'ar'->'a') = 'array'
      and jsonb_typeof(translations->'en'->'a') = 'array'
      and jsonb_array_length(translations->'ku'->'a') = 4
      and jsonb_array_length(translations->'fa'->'a') = 4
      and jsonb_array_length(translations->'ar'->'a') = 4
      and jsonb_array_length(translations->'en'->'a') = 4
    )
);

create unique index if not exists kh_quiz_bank_fingerprint_unique
  on public.kh_quiz_bank(content_fingerprint)
  where content_fingerprint is not null;

create index if not exists kh_quiz_bank_published_category_idx
  on public.kh_quiz_bank(category, id)
  where status = 'published';

create index if not exists kh_quiz_bank_status_id_idx
  on public.kh_quiz_bank(status, id);

alter table public.kh_quiz_bank enable row level security;

drop policy if exists kh_quiz_bank_published_read
  on public.kh_quiz_bank;

create policy kh_quiz_bank_published_read
  on public.kh_quiz_bank
  for select
  to authenticated
  using (status = 'published');

grant select on public.kh_quiz_bank to authenticated;

